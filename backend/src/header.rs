//! Generates `up60p.h`, the declarations Swift imports to call this library, from the Rust definitions: the options
//! struct comes from `options::FIELDS` and the status codes from `status::ALL`, so the header is a build product
//! and never edited by hand. `scripts/build-rust-backend.sh` writes it with `up60p --write-header <path>`.

use crate::options::{FIELDS, PATH_MAX};
use crate::status;

/// The C declarations of the functions exported by `lib.rs`, in the order they appear in the header.
pub const FUNCTIONS: &[(&str, &str)] = &[
    (
        "up60p_init",
        "/* Registers the log callback and checks that the media engine is present (UP60P_ERR_ENGINE_UNAVAILABLE if not). */\n\
         up60p_error up60p_init(const char *app_support_dir, up60p_log_callback log_cb);",
    ),
    ("up60p_default_options", "void up60p_default_options(up60p_options *out_opts);"),
    (
        "up60p_process_path",
        "/* Processes a file, or every video and image in a folder (recursively). Blocks until done; one run at a time.\n \
         * Writes <name>_[restored].mp4 (H.264, FLAC audio) or <name>_[restored].png into opts->outdir, or beside the\n \
         * input. */\n\
         up60p_error up60p_process_path(const char *input_path, const up60p_options *opts);",
    ),
    ("up60p_set_dry_run", "/* Non-zero: log the plan for each file instead of processing it. */\nvoid up60p_set_dry_run(int enable);"),
    (
        "up60p_request_cancel",
        "/* Stops a running up60p_process_path; it returns UP60P_ERR_CANCELLED and leaves no partial output. */\n\
         void up60p_request_cancel(void);",
    ),
    ("up60p_shutdown", "void up60p_shutdown(void);"),
    (
        "up60p_engine_version",
        "/* The media engine's version (static storage), or NULL when it is not linked. */\n\
         const char *up60p_engine_version(void);",
    ),
    ("up60p_options_size", "/* sizeof(up60p_options) as the library sees it. */\nsize_t up60p_options_size(void);"),
];

pub fn generate() -> String {
    let mut h = String::new();
    h += "/* Generated by myUpscaler's Rust backend (backend/src/header.rs). Do not edit. */\n";
    h += "#pragma once\n\n#include <stddef.h>\n\n#ifdef __cplusplus\nextern \"C\" {\n#endif\n\n";
    h += &format!("#define UP60P_PATH_MAX {PATH_MAX}\n\n");
    h += "typedef enum {\n";
    for (name, value) in status::ALL {
        h += &format!("    UP60P_{name} = {value},\n");
    }
    h += "} up60p_error;\n\n";
    h += "typedef struct {\n";
    for (name, size) in FIELDS {
        match size {
            Some(n) if *n == PATH_MAX => h += &format!("    char {name}[UP60P_PATH_MAX];\n"),
            Some(n) => h += &format!("    char {name}[{n}];\n"),
            None => h += &format!("    int {name};\n"),
        }
    }
    h += "} up60p_options;\n\n";
    h += "typedef void (*up60p_log_callback)(const char *message);\n\n";
    for (_, decl) in FUNCTIONS {
        h += decl;
        h += "\n\n";
    }
    h += "#ifdef __cplusplus\n}\n#endif\n";
    h
}

/// Writes the header only when its text changed, so Xcode does not rebuild the Swift sources needlessly.
pub fn write(path: &std::path::Path) -> std::io::Result<()> {
    let text = generate();
    if std::fs::read_to_string(path).ok().as_deref() == Some(text.as_str()) {
        return Ok(());
    }
    if let Some(dir) = path.parent() {
        std::fs::create_dir_all(dir)?;
    }
    std::fs::write(path, text)
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::options::Options;
    use std::ffi::{c_char, c_int};
    use std::mem::{align_of, size_of};

    #[test]
    fn declares_every_field_in_order_with_its_c_type() {
        let h = generate();
        let mut at = 0;
        for (name, size) in FIELDS {
            let decl = match size {
                Some(n) if *n == PATH_MAX => format!("char {name}[UP60P_PATH_MAX];"),
                Some(n) => format!("char {name}[{n}];"),
                None => format!("int {name};"),
            };
            let found = h[at..].find(&decl).unwrap_or_else(|| panic!("{decl} missing or out of order"));
            at += found + decl.len();
        }
    }

    #[test]
    fn field_list_matches_the_struct_layout() {
        // With repr(C), char arrays and ints laid out in FIELDS order give exactly this size: the C compiler that
        // reads the generated header computes the same.
        let mut offset = 0usize;
        for (_, size) in FIELDS {
            match size {
                Some(n) => offset += n * size_of::<c_char>(),
                None => offset = offset.next_multiple_of(align_of::<c_int>()) + size_of::<c_int>(),
            }
        }
        assert_eq!(offset.next_multiple_of(align_of::<Options>()), size_of::<Options>());
        assert_eq!(FIELDS.len(), 72);
    }

    #[test]
    fn declares_every_exported_function_and_status() {
        let h = generate();
        let lib = include_str!("lib.rs");
        let exported: Vec<&str> = lib
            .split("pub extern \"C\" fn ")
            .chain(lib.split("pub unsafe extern \"C\" fn "))
            .skip(1)
            .filter_map(|rest| rest.split('(').next())
            .filter(|n| n.starts_with("up60p_"))
            .collect();
        assert!(exported.len() >= 8, "{exported:?}");
        for name in exported {
            assert!(FUNCTIONS.iter().any(|(n, _)| *n == name), "{name} is exported but not declared");
            assert!(h.contains(&format!("{name}(")), "{name} missing from the header");
        }
        assert!(h.contains("UP60P_OK = 0,") && h.contains("UP60P_ERR_UNSUPPORTED_MEDIA = 7,"));
    }

    #[test]
    fn write_is_idempotent() {
        let path = std::env::temp_dir().join(format!("up60p-header-{}/up60p.h", std::process::id()));
        write(&path).unwrap();
        let first = std::fs::metadata(&path).unwrap().modified().unwrap();
        std::thread::sleep(std::time::Duration::from_millis(20));
        write(&path).unwrap();
        assert_eq!(std::fs::metadata(&path).unwrap().modified().unwrap(), first);
        assert_eq!(std::fs::read_to_string(&path).unwrap(), generate());
    }
}
